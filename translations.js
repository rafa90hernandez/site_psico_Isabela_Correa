function setLanguage(lang) {
  if (!translations[lang]) lang = "pt";
  const dictionary = translations[lang];

  document.documentElement.lang = lang === "pt" ? "pt-BR" : lang;
  document.title = dictionary.metaTitle;
  const metaDescription = document.querySelector('meta[name="description"]');
  if (metaDescription) metaDescription.setAttribute("content", dictionary.metaDescription);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) element.textContent = dictionary[key];
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const key = element.dataset.i18nAria;
    if (dictionary[key]) element.setAttribute("aria-label", dictionary[key]);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt;
    if (dictionary[key]) element.setAttribute("alt", dictionary[key]);
  });

  document.querySelectorAll(".lang-btn").forEach((button) => {
    const active = button.dataset.lang === lang;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", active ? "true" : "false");
  });

  const links = languageLinks[lang];
  const whatsappLinks = document.querySelectorAll('a[href*="wa.me/5534999942302"]');
  whatsappLinks.forEach((link) => {
    const isBooking = link.classList.contains("btn-primary") || link.classList.contains("whatsapp-float");
    link.href = "https://wa.me/5534999942302?text=" + encodeURIComponent(isBooking ? links.book : links.info);
  });

  const emailLink = document.querySelector('a[href^="mailto:isabela-correa@ups.br"]');
  if (emailLink) {
    emailLink.href = "mailto:isabela-correa@ups.br?subject=" + encodeURIComponent(links.emailSubject) + "&body=" + encodeURIComponent(links.emailBody);
  }

  localStorage.setItem("preferredLanguage", lang);
}

document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll(".lang-btn").forEach((button) => {
    button.addEventListener("click", () => setLanguage(button.dataset.lang));
  });

  setLanguage(localStorage.getItem("preferredLanguage") || "pt");
});
